import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { PNG } from 'pngjs'
import { expect, it } from 'vitest'
import { buildCompareModel } from '../../src/gallery/compare-model.js'
import { loadGalleryModel } from '../../src/gallery/model.js'
import { generateCompareGallery } from '../../src/gallery/generate-compare.js'
import { renderCompare } from '../../src/gallery/render-compare.js'
import { makeManifest, makeShot } from '../fixtures/manifest.js'

it('renders all seven verdict labels, gate summary, diff image, and run status', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'shotwright-compare-render-'))
  try {
    const write = (id: string, statuses: string[]): string => {
      const dir = path.join(root, id)
      fs.mkdirSync(path.join(dir, 'shots'), { recursive: true })
      fs.mkdirSync(path.join(dir, 'data'))
      fs.writeFileSync(path.join(dir, 'data', 'note.txt'), id === 'a' ? 'before' : 'after')
      const shots = statuses.map((name, index) => {
        const file = `shots/${name}.png`,
          image = new PNG({ width: name === 'size-changed' && id === 'b' ? 3 : 2, height: 2 })
        image.data.fill(
          index +
            (id === 'b' && name === 'changed' ? 200 : id === 'b' && name === 'similar' ? 1 : 0),
        )
        fs.writeFileSync(
          path.join(dir, file),
          name === 'unreadable' && id === 'a' ? Buffer.from('bad') : PNG.sync.write(image),
        )
        return makeShot({ name, spec: 'example.shots.ts', file })
      })
      fs.writeFileSync(
        path.join(dir, 'manifest.json'),
        JSON.stringify(
          makeManifest({
            runId: id,
            status: id === 'a' ? 'failed' : 'passed',
            shots,
            artifacts: [
              {
                spec: 'example.shots.ts',
                name: 'note',
                file: 'data/note.txt',
                contentType: 'text/plain',
                bytes: id === 'a' ? 6 : 5,
                testId: 'test-note',
              },
            ],
          }),
        ),
      )
      return dir
    }
    const a = write('a', [
      'identical',
      'similar',
      'changed',
      'size-changed',
      'removed',
      'unreadable',
    ])
    const b = write('b', ['identical', 'similar', 'changed', 'size-changed', 'added', 'unreadable'])
    const model = buildCompareModel(loadGalleryModel(a), loadGalleryModel(b), {
      aRunDir: a,
      bRunDir: b,
    })
    const html = renderCompare(model, true)
    const generated = generateCompareGallery(a, b, { failOnChange: true })
    let page = fs.readFileSync(generated.outputFile, 'utf8')
    expect(page).toBe(html)
    const summary = JSON.parse(
      fs.readFileSync(generated.outputFile.replace(/\.html$/, '.compare.json'), 'utf8'),
    ) as {
      version: string
      comparator: { name: string; version: string }
      runs: { a: { pathDigest: string }; b: { pathDigest: string } }
      provenance: { unavailable: string[] }
    }
    summary.runs.a.pathDigest = 'PATH'
    summary.runs.b.pathDigest = 'PATH'
    // The sidecar records the package and comparator versions; pin them by
    // shape, not by value, so a release bump cannot change the hash below.
    const packageVersion = (
      JSON.parse(fs.readFileSync(new URL('../../package.json', import.meta.url), 'utf8')) as {
        version: string
      }
    ).version
    expect(summary.version).toBe(packageVersion)
    expect(summary.comparator.name).toBe('pixelmatch')
    expect(summary.comparator.version).toMatch(/^\d+\.\d+\.\d+$/)
    summary.version = 'VERSION'
    summary.comparator.version = 'VERSION'
    const sha256 = (value: string): string => createHash('sha256').update(value).digest('hex')
    // The footer carries the package version too; assert it, then pin the page
    // with the version masked, for the same release-bump reason.
    expect(page).toContain(`<p class="source">Generated by shotwright ${packageVersion} · `)
    page = page.replace(
      `<p class="source">Generated by shotwright ${packageVersion} · `,
      '<p class="source">Generated by shotwright VERSION · ',
    )
    // Fixture runs record no provenance; the advisory banner says so and the
    // compare.json provenance carries the same strings.
    expect(page).toContain(
      `<p class="provenance">Render environment provenance incomplete: ${summary.provenance.unavailable.join('; ')}</p>`,
    )
    expect(sha256(page)).toMatchInlineSnapshot(
      `"97fd2ff333606c3556d59bd1a11ec83c2ed691ce27bab651c5e92212b51a8fd9"`,
    )
    expect(sha256(JSON.stringify(summary, null, 2) + '\n')).toMatchInlineSnapshot(
      `"25921cb2341aa0cab3aef4ce30ad07ac37f01a467bbc20b4d45110ed6f0edcb8"`,
    )
    for (const state of [
      'identical',
      'similar',
      'changed',
      'size-changed',
      'added',
      'removed',
      'unreadable',
    ])
      expect(html).toContain(`state-${state}`)
    expect(model.pairs[0]?.state).toBe('changed')
    expect(html).toContain('Gate:')
    expect(html).toContain('@media (prefers-color-scheme: dark)')
    expect(html).toContain('.pair.state-similar.gated{border-left-color:var(--state-gated)}')
    expect(html).toContain('A run: failed · B run: passed')
    expect(html).toContain('data:image/png;base64,')
    expect(html).toContain(
      "style-src 'unsafe-inline'; script-src 'unsafe-inline'; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'",
    )
    expect(html.match(/<script>/g)).toHaveLength(1)
    expect(html).not.toContain('<script src=')
    expect(html.match(/data-viewer-open="pair-\d+-(?:a|b|diff)"/g)?.length).toBeGreaterThan(0)
    expect(html.match(/data:image\/png;base64,/g)).toHaveLength((html.match(/<img /g) ?? []).length)
    expect(html).toContain('fail-on-change on')
    expect(html).toContain(
      '<a href="../a/shots/identical.png" download="identical.png">Download A</a>',
    )
    expect(html).toContain(
      '<a href="../b/shots/identical.png" download="identical.png">Download B</a>',
    )
    expect(html.match(/Sibling-file warning:/g)).toHaveLength(model.pairs.length)
    const custom = renderCompare(model, true, { aBase: '../run a', bBase: '../run b' })
    expect(custom).toContain(
      '<a href="../run%20a/shots/identical.png" download="identical.png">Download A</a>',
    )
    expect(custom).toContain(
      '<a href="../run%20b/shots/identical.png" download="identical.png">Download B</a>',
    )
  } finally {
    fs.rmSync(root, { recursive: true, force: true })
  }
})

it('links Download A / Download B to the sibling files for text, JSON and binary artifact pairs', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'shotwright-compare-links-'))
  try {
    const files = {
      'page.html': ['text/html', '<p>a</p>', '<p>b</p>'],
      'reading.json': ['application/json', '{"a":1}', '{"a":2}'],
      'book of sheets.xlsx': ['application/octet-stream', 'PK-a', 'PK-b'],
    } as const
    const write = (id: string, side: 1 | 2): string => {
      const dir = path.join(root, id)
      fs.mkdirSync(path.join(dir, 'data'), { recursive: true })
      const artifacts = Object.entries(files).map(([name, row]) => {
        fs.writeFileSync(path.join(dir, 'data', name), row[side])
        return {
          spec: 'data.shots.ts',
          name,
          file: `data/${name}`,
          contentType: row[0],
          bytes: row[side].length,
          testId: 'test-data',
        }
      })
      fs.writeFileSync(
        path.join(dir, 'manifest.json'),
        JSON.stringify(makeManifest({ runId: id, artifacts })),
      )
      return dir
    }
    const a = write('run-a', 1),
      b = write('run-b', 2)
    const model = buildCompareModel(loadGalleryModel(a), loadGalleryModel(b), {
      aRunDir: a,
      bRunDir: b,
    })
    expect(model.pairs.map((pair) => pair.state)).toEqual(['changed', 'changed', 'changed'])
    const links = (html: string): string[] =>
      [...html.matchAll(/<a class="download" href="([^"]+)" download>(Download [AB])<\/a>/g)].map(
        (match) => `${match[2]} ${match[1]}`,
      )
    // Default layout: the page lives in <outputDir>/compare/ beside the run directories.
    const html = renderCompare(model)
    expect(links(html)).toEqual([
      'Download A ../run-a/data/page.html',
      'Download B ../run-b/data/page.html',
      'Download A ../run-a/data/reading.json',
      'Download B ../run-b/data/reading.json',
      'Download A ../run-a/data/book%20of%20sheets.xlsx',
      'Download B ../run-b/data/book%20of%20sheets.xlsx',
    ])
    expect(html.match(/Sibling-file warning:/g)).toHaveLength(3)
    expect(html).toContain(
      'Each download link requires this gallery beside the run directory for its side.',
    )
    // A caller-chosen output file gets paths relative to where it was written.
    fs.mkdirSync(path.join(root, 'review'))
    const generated = generateCompareGallery(a, b, {
      outputFile: path.join(root, 'review', 'compare.html'),
    })
    expect(links(fs.readFileSync(generated.outputFile, 'utf8')).slice(0, 2)).toEqual([
      'Download A ../run-a/data/page.html',
      'Download B ../run-b/data/page.html',
    ])
  } finally {
    fs.rmSync(root, { recursive: true, force: true })
  }
})

it('marks exactly the cards the gate counts, derived from the same predicate as the header', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'shotwright-compare-gated-'))
  try {
    const write = (id: string): string => {
      const dir = path.join(root, id)
      fs.mkdirSync(path.join(dir, 'shots'), { recursive: true })
      fs.mkdirSync(path.join(dir, 'data'))
      const shots = ['same', 'tint'].map((name) => {
        const image = new PNG({ width: 2, height: 2 })
        image.data.fill(name === 'tint' && id === 'b' ? 1 : 0)
        fs.writeFileSync(path.join(dir, `shots/${name}.png`), PNG.sync.write(image))
        return makeShot({ name, spec: 'example.shots.ts', file: `shots/${name}.png` })
      })
      const artifacts = ['kept', 'noisy'].map((name) => {
        fs.writeFileSync(path.join(dir, 'data', `${name}.txt`), `${name}-${id}`)
        return {
          spec: 'example.shots.ts',
          name,
          file: `data/${name}.txt`,
          contentType: 'text/plain',
          bytes: name.length + 2,
          testId: 'test-note',
        }
      })
      fs.writeFileSync(
        path.join(dir, 'manifest.json'),
        JSON.stringify(makeManifest({ runId: id, shots, artifacts })),
      )
      return dir
    }
    const a = write('a'),
      b = write('b')
    const cards = (html: string): string[] =>
      html
        .split('<article ')
        .slice(1)
        .map((card) => card.slice(0, card.indexOf('</header>')))
    const marked = (html: string): number => (html.match(/ · counted by gate</g) ?? []).length
    const gatedCount = (html: string): number => Number(/gated pairs (\d+)/.exec(html)?.[1])
    const find = (html: string, name: string): string =>
      cards(html).find((card) => card.includes(`/ ${name}</h2>`))!

    const strict = fs.readFileSync(
      generateCompareGallery(a, b, {
        strict: true,
        ignore: ['example.shots.ts/noisy'],
        outputFile: path.join(root, 'strict.html'),
      }).outputFile,
      'utf8',
    )
    expect(find(strict, 'tint')).toContain('shot · similar · counted by gate')
    expect(find(strict, 'tint')).toContain('state-similar gated')
    expect(find(strict, 'kept')).toContain('artifact · changed · counted by gate')
    expect(find(strict, 'noisy')).toContain('artifact · changed · ignored for gate')
    expect(find(strict, 'noisy')).not.toContain('counted by gate')
    expect(find(strict, 'same')).not.toContain('counted by gate')
    expect(marked(strict)).toBe(gatedCount(strict))
    expect(gatedCount(strict)).toBe(2)

    const lenient = fs.readFileSync(
      generateCompareGallery(a, b, {
        ignore: ['example.shots.ts/noisy'],
        outputFile: path.join(root, 'lenient.html'),
      }).outputFile,
      'utf8',
    )
    expect(find(lenient, 'tint')).not.toContain('counted by gate')
    expect(find(lenient, 'tint')).not.toContain(' gated')
    expect(marked(lenient)).toBe(gatedCount(lenient))
    expect(gatedCount(lenient)).toBe(1)

    // The in-memory renderer takes the same flag and agrees with the generator.
    const model = buildCompareModel(loadGalleryModel(a), loadGalleryModel(b), {
      aRunDir: a,
      bRunDir: b,
    })
    for (const strictFlag of [false, true]) {
      const html = renderCompare(model, false, {}, strictFlag)
      expect(marked(html)).toBe(gatedCount(html))
    }
  } finally {
    fs.rmSync(root, { recursive: true, force: true })
  }
})

it('explains an empty comparison without changing verdict totals', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'shotwright-empty-compare-'))
  try {
    const dirs = ['a', 'b'].map((id) => {
      const dir = path.join(root, id)
      fs.mkdirSync(dir)
      fs.writeFileSync(path.join(dir, 'manifest.json'), JSON.stringify(makeManifest({ runId: id })))
      return dir
    })
    const model = buildCompareModel(loadGalleryModel(dirs[0]!), loadGalleryModel(dirs[1]!), {
      aRunDir: dirs[0]!,
      bRunDir: dirs[1]!,
    })
    const html = renderCompare(model)
    expect(html).toContain('No pairs to compare')
    expect(html).toContain('gated pairs 0')
  } finally {
    fs.rmSync(root, { recursive: true, force: true })
  }
})
