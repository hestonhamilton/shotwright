import fs from 'node:fs'
import { describe, expect, it } from 'vitest'
import { buildCompareModel } from '../../src/gallery/compare-model.js'
import { renderCompare } from '../../src/gallery/render-compare.js'
import { renderGallery, sourceLine } from '../../src/gallery/render.js'
import { browsableRepositoryUrl } from '../../src/version.js'
import { makeManifest } from '../fixtures/manifest.js'

// The expected strings are derived from package.json, never typed in, so a
// release bump or a repository move cannot break these tests.
const pkg = JSON.parse(fs.readFileSync(new URL('../../package.json', import.meta.url), 'utf8')) as {
  version: string
  license: string
  repository: { url: string }
}
const url = pkg.repository.url.replace(/^git\+/, '').replace(/\.git$/, '')
const line = `Generated by shotwright ${pkg.version} · ${pkg.license} · source: <a href="${url}" rel="noopener noreferrer">${url}</a>`

const side = (m = makeManifest()) => ({
  manifest: m,
  specs: [],
  diagnostics: [],
  manifestByteLength: 1,
  sourceManifestVersion: 2 as const,
})

describe('source footer', () => {
  it('renders on the gallery from package.json', () => {
    const html = renderGallery(side())
    expect(html).toContain(`<p class="source">${line}</p>`)
    expect(html).toContain('</footer>')
  })

  it('renders on the compare sheet from package.json', () => {
    const html = renderCompare(buildCompareModel(side(), side()))
    expect(html).toContain(`<footer><p class="source">${line}</p></footer></main>`)
  })

  it('escapes interpolated values and never leaves an unsafe href', () => {
    const html = sourceLine({ version: '1<b>', license: 'A&B', url: 'https://x.test/"><i>' })
    expect(html).not.toContain('<b>')
    expect(html).not.toContain('<i>')
    expect(html).toContain('1&lt;b&gt;')
    expect(html).toContain('A&amp;B')
    expect(sourceLine({ version: '1', license: 'L', url: null })).toContain('source: not recorded')
    expect(sourceLine({ version: '1', license: 'L', url: null })).not.toContain('<a ')
  })

  it('normalises repository URLs and rejects non-http schemes', () => {
    expect(browsableRepositoryUrl('git+https://example.test/o/r.git')).toBe(
      'https://example.test/o/r',
    )
    expect(browsableRepositoryUrl('javascript:alert(1)')).toBeNull()
    expect(browsableRepositoryUrl(undefined)).toBeNull()
  })
})
